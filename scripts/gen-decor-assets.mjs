#!/usr/bin/env node
// Generates app/decor-assets.css: the geometric ornaments for the #105 decor directions,
// computed from geometry (no hand-drawn paths). Usage: node scripts/gen-decor-assets.mjs 
// B: khatam (octagram) lattice on a square grid.
// C: tazhib-style double-rule frame (border-image) and an octagram medallion.
import { writeFileSync } from "node:fs";

const GOLD = "#c6a15b";
const GREEN = "#17473b";
const f = (n) => +n.toFixed(2);

function regular(center, n, circumradius, phase) {
  return Array.from({ length: n }, (_, k) => {
    const a = phase + (2 * Math.PI * k) / n;
    return [center[0] + circumradius * Math.cos(a), center[1] + circumradius * Math.sin(a)];
  });
}

// Khatam lattice: the octagram outline {8/2} (union of two squares at 0 and 45 degrees) on every point of a
// square grid, axis tips of neighbours meeting at the pitch midpoint. Tile is 100 units; tip radius 50.
const INNER = (50 * Math.SQRT1_2) / Math.cos(Math.PI / 8); // where the two squares' edges cross
function star([x, y]) {
  const tips = regular([x, y], 8, 50, 0);
  const dips = regular([x, y], 8, INNER, Math.PI / 8);
  return tips.map((t, i) => `${i ? "L" : "M"}${f(t[0])} ${f(t[1])}L${f(dips[i][0])} ${f(dips[i][1])}`).join("") + "Z";
}
const latticePath = () => [[0, 0], [100, 0], [0, 100], [100, 100]].map(star).join("");

const uri = (svg) => `url("data:image/svg+xml,${encodeURIComponent(svg.replace(/\s+/g, " ").trim())}")`;
const tile = (color) =>
  uri(`<svg xmlns='http://www.w3.org/2000/svg' width='100' height='100' viewBox='0 0 100 100' fill='none' stroke='${color}' stroke-width='1.1' stroke-linecap='square' stroke-linejoin='miter'><path d='${latticePath()}'/></svg>`);

// C: frame source 96x96, 32-unit corner slices. Corner = rounded outer rule + inner rule + diamond finial.
const frame = (color) =>
  uri(`<svg xmlns='http://www.w3.org/2000/svg' width='96' height='96' viewBox='0 0 96 96' fill='none' stroke='${color}' stroke-linecap='butt'>
<path d='M32 6H15.5A9.5 9.5 0 0 0 6 15.5V32M64 6H80.5A9.5 9.5 0 0 1 90 15.5V32M32 90H15.5A9.5 9.5 0 0 1 6 80.5V64M64 90H80.5A9.5 9.5 0 0 0 90 80.5V64' stroke-width='1.4'/>
<path d='M32 12H17A5 5 0 0 0 12 17V32M64 12H79A5 5 0 0 1 84 17V32M32 84H17A5 5 0 0 1 12 79V64M64 84H79A5 5 0 0 0 84 79V64' stroke-width='.8'/>
<path d='M32 6H64M32 90H64M6 32V64M90 32V64' stroke-width='1.4'/><path d='M32 12H64M32 84H64M12 32V64M84 32V64' stroke-width='.8'/>
<path d='M21 17.6 24.4 21 21 24.4 17.6 21Z' fill='${color}' stroke='none'/>
<path d='M75 17.6 78.4 21 75 24.4 71.6 21Z' fill='${color}' stroke='none'/>
<path d='M21 71.6 24.4 75 21 78.4 17.6 75Z' fill='${color}' stroke='none'/>
<path d='M75 71.6 78.4 75 75 78.4 71.6 75Z' fill='${color}' stroke='none'/></svg>`);

// C: medallion 64x64: seal disc, two rings, octagram {8/2} (two squares).
function medallion(fill, color) {
  const sq = (rad, ph) => regular([32, 32], 4, rad, ph).map((p, i) => `${i ? "L" : "M"}${f(p[0])} ${f(p[1])}`).join("") + "Z";
  return uri(`<svg xmlns='http://www.w3.org/2000/svg' width='64' height='64' viewBox='0 0 64 64' fill='none' stroke='${color}'>
<circle cx='32' cy='32' r='30.5' fill='${fill}' stroke-width='1.2'/><circle cx='32' cy='32' r='26' stroke-width='.7'/>
<path d='${sq(17, 0)}${sq(17, Math.PI / 4)}' stroke-width='1' stroke-linejoin='miter'/><circle cx='32' cy='32' r='3' stroke-width='.8'/></svg>`);
}

const css = `/* GENERATED by scripts/gen-decor-assets.mjs for #105 (decor directions B and C). Do not edit by hand. */
:root {
  --decor-lattice-gold: ${tile(GOLD)};
  --decor-lattice-green: ${tile(GREEN)};
  --decor-frame-gold: ${frame(GOLD)};
  --decor-medallion: ${medallion("#0d332a", GOLD)};
}
`;
if (process.argv[2] === "preview") {
  writeFileSync(process.argv[3], `<style>body{margin:0;background:#0d332a}div{width:1000px;height:560px;background:${tile(GOLD)};background-size:100px 100px}</style><div></div>`);
} else writeFileSync(new URL("../app/decor-assets.css", import.meta.url), css);
